# Función para calcular el área de un trapecio
def calcular_area(base_mayor, base_menor, altura):
    return (base_mayor + base_menor) * altura / 2

# Función para calcular el perímetro de un trapecio
def calcular_perimetro(base_mayor, base_menor, lado_1, lado_2):
    return base_mayor + base_menor + lado_1 + lado_2
